#!/usr/bin/env python3
"""Install the bundled "Arc Look" Zen mod into a closed Zen profile."""

from __future__ import annotations

import json
import logging
import shutil
from datetime import datetime
from pathlib import Path
from typing import Any, Dict

from .sessions import resolve_zen_profile
from .zen_prefs import set_user_prefs

logger = logging.getLogger(__name__)

MOD_SOURCE = Path(__file__).resolve().parent / "mods" / "arc-look"

# The mod styles the address bar for Zen's "always floating" mode, as in Arc
MOD_ZEN_PREFS = {"zen.urlbar.behavior": "float"}
MOD_ID = "a0c5c3b9-8036-4004-ba02-ce2b74e41254"
MOD_META = {
    "id": MOD_ID,
    "name": "Arc Look",
    "description": "Zen tweaks towards Arc: container line on the left, compact top bar, Arc-like address bar and Peek.",
    "image": "",
    "author": "nosefu",
    "version": "1.4.1",
    "tags": ["arc", "urlbar", "toolbar"],
    "createdAt": "2026-10-23",
    "updatedAt": "2026-10-23",
    "enabled": True,
}


def rebuild_mods_stylesheet(profile: Path, registry: Dict[str, Any]) -> None:
    """Write chrome/zen-themes.css the way ZenMods does.

    Zen only reads this file at startup and rebuilds it when mods change in its
    settings, so a mod added from outside would stay inactive without this.
    """
    stamp = datetime.now().strftime("%A, %B %d, %Y at %I:%M:%S %p")
    parts = [
        "/* Zen Mods - Generated by ZenMods.\n"
        f"* FILE GENERATED AT: {stamp}\n"
        "* DO NOT EDIT THIS FILE DIRECTLY!\n"
        "* Your changes will be overwritten.\n"
        "* Instead, go to the preferences and edit the mods there.\n"
        "*/\n"
    ]
    for mod in registry.values():
        if mod.get("enabled") is False:
            continue
        css = profile / "chrome" / "zen-themes" / mod["id"] / "chrome.css"
        if not css.exists():
            continue
        parts.append(f"\n/* Name: {mod.get('name', '')} */\n")
        parts.append(f"/* Description: {mod.get('description', '')} */\n")
        parts.append(f"/* Author: @{mod.get('author', '')} */\n")
        parts.append(css.read_text(encoding="utf-8"))
    parts.append("\n/* End of Zen Mods */\n")
    (profile / "chrome").mkdir(exist_ok=True)
    (profile / "chrome" / "zen-themes.css").write_text("".join(parts), encoding="utf-8")


def mod_default_prefs() -> Dict[str, Any]:
    """Default values of the mod's settings; Zen sets them only when it rebuilds mods itself."""
    with open(MOD_SOURCE / "preferences.json", encoding="utf-8") as f:
        entries = json.load(f)
    defaults = {}
    for entry in entries:
        value = entry.get("defaultValue")
        if entry.get("type") == "checkbox":
            defaults[entry["property"]] = bool(value)
        elif entry.get("type") == "string" and value:
            defaults[entry["property"]] = value
    return defaults


def install_arc_look_mod(zen_profile: str | Path | None = None, create_backups: bool = True) -> bool:
    profile = resolve_zen_profile(zen_profile)
    if not (MOD_SOURCE / "chrome.css").exists():
        logger.error(f"❌ Bundled mod not found: {MOD_SOURCE}")
        return False

    registry_path = profile / "zen-themes.json"
    stylesheet = profile / "chrome" / "zen-themes.css"
    if create_backups:
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        for path in (registry_path, stylesheet):
            if path.exists():
                shutil.copy2(path, path.with_name(f"{path.name}.codex-mod-backup-{stamp}"))

    target = profile / "chrome" / "zen-themes" / MOD_ID
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(MOD_SOURCE, target)

    registry = json.loads(registry_path.read_text(encoding="utf-8")) if registry_path.exists() else {}
    base = target.as_uri()
    # A reinstall keeps the mod switched off if the user turned it off
    enabled = registry.get(MOD_ID, {}).get("enabled", True)
    registry[MOD_ID] = {
        **MOD_META,
        "enabled": enabled,
        "homepage": base,
        "style": f"{base}/chrome.css",
        "readme": f"{base}/readme.md",
        "preferences": f"{base}/preferences.json",
    }
    registry_path.write_text(json.dumps(registry, ensure_ascii=False), encoding="utf-8")
    rebuild_mods_stylesheet(profile, registry)

    # Keep settings the user already changed; only fill in the defaults
    prefs_js = (profile / "prefs.js").read_text(encoding="utf-8") if (profile / "prefs.js").exists() else ""
    missing = {name: value for name, value in mod_default_prefs().items() if f'user_pref("{name}",' not in prefs_js}
    set_user_prefs(profile, {**missing, **MOD_ZEN_PREFS}, create_backups=create_backups)
    logger.info("   Address bar: always floating (zen.urlbar.behavior = float)")
    logger.info(f"Done. Arc Look mod {MOD_META['version']} installed, {len(missing)} mod settings set to defaults.")
    return True
